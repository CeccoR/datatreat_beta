// Own-property lookup: a CIF label such as 'constructor' must not hit Object.prototype.
const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);

// Leading element symbol of a CIF type symbol or label, case-insensitively ('TI' → 'Ti').
// Two letters win when they spell an element, so 'Sr0' is strontium and 'Ow1' oxygen —
// the usual reading of CIF labels. 'D' (deuterium) has no entry of its own: kept as 'D'
// here and mapped to H by the caller. null when no symbol fits.
function leadingSymbol(str){
  const m = /^([A-Za-z])([A-Za-z]?)/.exec(str);
  if (!m) return null;
  const one = m[1].toUpperCase();
  if (m[2]){ const two = one + m[2].toLowerCase(); if (has(ELEMENTS, two)) return two; }
  return (has(ELEMENTS, one) || one === 'D') ? one : null;
}

// The f0 table key for a CIF `_atom_site_type_symbol` (or, lacking one, the site label).
// Charges are read in both orders ('Ti4+', 'Ti+4', 'O2-', 'O-2', 'O-', 'Fe++'); without a
// sign the trailing characters are a label suffix and dropped ('Sr0', 'O2', 'Ti1a' → neutral).
// An ion WK did not fit (or a fractional valence such as 'Fe2.5+') falls back to the neutral
// atom with fallback:true, so the page can say so instead of failing the whole phase.
// Returns { key, element, ion, fallback, charge } or null when no scattering factor exists.
function speciesKey(label){
  if (typeof label !== 'string') return null;
  const str = label.trim().replace(/[\u2212\u2013]/g, '-');   // typographic minus from pasted text
  if (!str) return null;
  // Exact table keys first: the fast path for already-normalised input, and the only way to
  // reach the valence variants 'Cval' / 'Siva'.
  if (has(F0, str)){
    const el = leadingSymbol(str);
    const ion = /[+-]$/.test(str);
    const q = ion ? (str.endsWith('-') ? -1 : 1)*(parseInt(str.slice(el.length), 10) || 1) : 0;
    return { key:str, element:el, ion, fallback:false, charge:q };
  }
  let el = leadingSymbol(str);
  if (!el) return null;
  const rest = str.slice(el.length);
  if (el === 'D') el = 'H';   // deuterium scatters X-rays exactly as hydrogen (same electron count)
  if (!has(F0, el)) return null;   // Z > 98: no Waasmaier–Kirfel fit
  let q = 0;
  const m = /^(\d+(?:\.\d*)?)?([+-])(\d+(?:\.\d*)?)?$/.exec(rest);
  if (m && !(m[1] && m[3])) q = (m[2] === '-' ? -1 : 1)*parseFloat(m[1] || m[3] || '1');
  else if (/^(\+\++|-+)$/.test(rest)) q = (rest[0] === '-' ? -1 : 1)*rest.length;
  if (!q) return { key:el, element:el, ion:false, fallback:false, charge:0 };
  const key = el + Math.abs(q) + (q < 0 ? '-' : '+');
  if (Number.isInteger(q) && has(F0, key)) return { key, element:el, ion:true, fallback:false, charge:q };
  return { key:el, element:el, ion:false, fallback:true, charge:q };
}

// Non-dispersive form factor (electrons) at s = sinθ/λ (Å⁻¹). `key` is an F0 key; anything
// else is resolved through speciesKey (slower, so callers in loops should pass the key).
// NaN for an unknown species, so a bad site shows up instead of silently scattering nothing.
function f0(key, s){
  let p = has(F0, key) ? F0[key] : null;
  if (!p){ const sp = speciesKey(key); if (!sp) return NaN; p = F0[sp.key]; }
  const s2 = s*s;
  return p[0]*Math.exp(-p[1]*s2) + p[2]*Math.exp(-p[3]*s2) + p[4]*Math.exp(-p[5]*s2)
       + p[6]*Math.exp(-p[7]*s2) + p[8]*Math.exp(-p[9]*s2) + p[10];
}

// [f′, f″] for an element at a characteristic line (a fresh array: callers may keep it).
// Ion keys and odd casing resolve to the element — dispersion is an inner-shell effect, the
// valence state barely moves it. Unknown element or line → [0, 0] (no anomalous term).
function fprime(element, line){
  let row = has(FP, element) ? FP[element] : null;
  if (!row){ const sp = speciesKey(element); row = sp && has(FP, sp.element) ? FP[sp.element] : null; }
  const v = row && has(row, line) ? row[line] : null;
  return v ? [v[0], v[1]] : [0, 0];
}

// The tabulated line nearest to λ (Å), or null when none is within LINE_TOL. Cu Kα1 and
// Kα2 are 0.0038 Å apart, so the nearest-line rule separates them.
function lineForWavelength(lam){
  if (!(lam > 0)) return null;
  let best = null, bd = Infinity;
  for (const ln of LINE_ORDER){ const d = Math.abs(LINES[ln] - lam); if (d < bd){ bd = d; best = ln; } }
  return bd <= LINE_TOL ? best : null;
}

// Standard atomic weight (g/mol), for the cell mass in Hill–Howard weight fractions. Labels
// and odd casing resolve like speciesKey. 'D' keeps its own mass (speciesKey maps it to H
// for scattering, but a deuterated cell would otherwise weigh light). NaN if unknown.
function atomicMass(element){
  if (has(ELEMENTS, element)) return ELEMENTS[element][1];
  const el = typeof element === 'string' ? leadingSymbol(element.trim()) : null;
  if (el === 'D') return 2.014102;
  return el ? ELEMENTS[el][1] : NaN;
}

