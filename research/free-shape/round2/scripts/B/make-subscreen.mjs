// The sub-screen: 22 rows of the screening set, 2 per Laue class, by a fixed rule written
// with the list to subscreen.txt. Classes in the protocol's order (i = 0…10), solids in the
// design's order S = box, sqbox, cylinder, ellcyl, ellipsoid, spheroid; class i takes the
// screening truths of S[2i mod 6] and S[(2i + 1) mod 6]. Spheres are not in it.
import fs from 'node:fs';
const d = JSON.parse(fs.readFileSync('../design/design.json', 'utf8'));
const L = ['-1', '2/m', 'mmm', '4/m', '4/mmm', '-3', '-3m', '6/m', '6/mmm', 'm-3', 'm-3m'];
const S = ['box', 'sqbox', 'cylinder', 'ellcyl', 'ellipsoid', 'spheroid'];
const rows = [];
L.forEach((l, i)=> { for (const s of [S[(2*i) % 6], S[(2*i + 1) % 6]]){ const r = d.rows.find(r=> r.screen && r.kind === 'truth' && r.laue === l && r.solid === s); if (!r || r.split !== 'tuning') throw new Error('no ' + l + ' ' + s); rows.push(r); } });
const cnt = (f) => rows.reduce((m, r)=> (m[f(r)] = (m[f(r)] || 0) + 1, m), {});
const txt = [
  '# Track B sub-screen: 22 rows of the 77-run screening set (design fs2-design-v1, revision 2).',
  '# Rule (fixed before any run): classes in the protocol\'s order i = 0..10 (-1, 2/m, mmm, 4/m, 4/mmm, -3, -3m, 6/m, 6/mmm, m-3, m-3m);',
  '# solids S = box, sqbox, cylinder, ellcyl, ellipsoid, spheroid; class i takes its screening truths of S[2i mod 6] and S[(2i+1) mod 6].',
  '# No spheres. The same list for every variant. Generated by make-subscreen.mjs.',
  `# solids: ${JSON.stringify(cnt(r=> r.solid))}; errors: ${JSON.stringify(cnt(r=> r.error ? r.error.kind : 'none'))}; orientations: ${JSON.stringify(cnt(r=> r.orient))}`,
  ...rows.map(r=> `${r.id}\t${r.laue}\t${r.solid}\t${r.orient}\t${r.error ? r.error.kind + ' ' + r.error.strength.toFixed(2) : 'none'}`)];
fs.writeFileSync('subscreen.txt', txt.join('\n') + '\n');
console.log(txt.join('\n'));
