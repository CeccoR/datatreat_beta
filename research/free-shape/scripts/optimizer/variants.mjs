/* The optimiser variants tried (methods/opt.mjs make(cfg)). node variants.mjs writes
   methods/v-<name>.mjs for each, so that run.mjs and batch.mjs can load them by file. */
import fs from 'node:fs';
import path from 'node:path';
const HERE = path.dirname(new URL(import.meta.url).pathname);
const nc = { noCov: true };
const all6 = o => ({ brief: o, full: o, polish: o, exact: o, held: o, refit: o });
export const VARIANTS = {
  // the app's search through the copy (must equal the baseline)
  app: {},
  // no covariance where nobody reads it (brief, full, polish, exact, held, refit), the
  // returned fit's once at the end
  nocov: { x: all6(nc), finalCov: true },
  // forward differences
  fwd: { x: all6({ ...nc, fwd: true }), finalCov: true },
  fwdBrief: { x: { ...all6(nc), brief: { ...nc, fwd: true } }, finalCov: true },
  // the member pass for W, R, X_s, B, occ (the rest central / forward)
  member: { x: all6({ ...nc, member: true }), finalCov: true },
  memberFwd: { x: all6({ ...nc, member: true, fwd: true }), finalCov: true },
  // Broyden's update, a fresh Jacobian every k iterations
  broy3: { x: all6({ ...nc, broyden: 3 }), finalCov: true },
  broy3Brief: { x: { ...all6(nc), brief: { ...nc, broyden: 3 } }, finalCov: true },
  broy8Brief: { x: { ...all6(nc), brief: { ...nc, broyden: 8 } }, finalCov: true },
  // the brief stage with fewer parameters free
  briefShapeXs: { x: all6(nc), finalCov: true, briefFree: 'shapeXs' },
  briefShape: { x: all6(nc), finalCov: true, briefFree: 'shape' },
  // fewer brief iterations / successive halving
  brief4: { x: all6(nc), finalCov: true, briefIter: 4 },
  halving: { x: all6(nc), finalCov: true, halving: { rungs: [2, 4, 8], keep: [6, 3] } },
  // log widths
  logW: { x: all6(nc), finalCov: true, logW: true },
  // the brief stage on every 2nd / 3rd point
  stride2: { x: all6(nc), finalCov: true, stride: 2 },
  stride3: { x: all6(nc), finalCov: true, stride: 3 },
  // distinct full refinements
  dedup: { x: all6(nc), finalCov: true, dedupFull: true },
  // the lattice frames screened briefly, the best refined fully
  heldBrief: { x: all6(nc), finalCov: true, heldBrief: { iter: 6, keep: 1 } },
  // multi-fidelity: each start fitted to the peak widths first, then 8 or 4 brief iterations
  sur8: { x: all6(nc), finalCov: true, surrogate: { iter: 30 } },
  sur4: { x: all6(nc), finalCov: true, surrogate: { iter: 30 }, briefIter: 4 },
  // halving with the candidates deduplicated modulo symmetry at each cut
  halvingDedup: { x: all6(nc), finalCov: true, halving: { rungs: [2, 4, 8], keep: [6, 3], dedup: true } },
  // combinations
  c1: { x: all6({ ...nc, fwd: true }), finalCov: true, halving: { rungs: [2, 4, 8], keep: [6, 3] } },
  c2: { x: all6({ ...nc, fwd: true }), finalCov: true, halving: { rungs: [2, 4, 8], keep: [6, 3] }, briefFree: 'shapeXs' },
  c3: { x: all6({ ...nc, fwd: true }), finalCov: true, halving: { rungs: [2, 4, 8], keep: [6, 3] }, briefFree: 'shapeXs', heldBrief: { iter: 6, keep: 1 } },
  // c1 and one more knob each
  c4: { x: all6({ ...nc, fwd: true }), finalCov: true, halving: { rungs: [2, 4, 8], keep: [6, 3] }, heldBrief: { iter: 6, keep: 1 } },
  c5: { x: { ...all6({ ...nc, fwd: true, broyden: 3 }), brief: { ...nc, fwd: true } }, finalCov: true, halving: { rungs: [2, 4, 8], keep: [6, 3] } },
  c6: { x: all6({ ...nc, fwd: true }), finalCov: true, halving: { rungs: [2, 4, 8], keep: [6, 3] }, stride: 2 },
  c7: { x: all6({ ...nc, fwd: true }), finalCov: true, halving: { rungs: [2, 4, 8], keep: [5, 2] }, nFull: 2 },
  // forward differences and Broyden's update, no start cut early: everywhere / brief only
  c8: { x: all6({ ...nc, fwd: true, broyden: 3 }), finalCov: true },
  c9: { x: { ...all6({ ...nc, fwd: true }), brief: { ...nc, fwd: true, broyden: 3 } }, finalCov: true },
  // the savings spent on more starts: 21 starts, halving keeps 10 then 4 (dedup: distinct ones)
  c10: { x: all6({ ...nc, fwd: true }), finalCov: true, starts: 20, halving: { rungs: [2, 4, 8], keep: [10, 4] } },
  c11: { x: all6({ ...nc, fwd: true }), finalCov: true, starts: 20, halving: { rungs: [2, 4, 8], keep: [10, 4], dedup: true } },
  // c1 cutting on the predicted minimum instead of the χ² reached
  c12: { x: all6({ ...nc, fwd: true }), finalCov: true, halving: { rungs: [2, 4, 8], keep: [6, 3], rank: 'pred' } },
  // gentler halving: 4 iterations before the one cut
  c13: { x: all6({ ...nc, fwd: true }), finalCov: true, halving: { rungs: [4, 8], keep: [5] } },
};
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)){
  const only = process.argv.slice(2);
  for (const [name, cfg] of Object.entries(VARIANTS)){
    if (only.length && !only.includes(name)) continue;
    fs.writeFileSync(path.join(HERE, 'methods', `v-${name}.mjs`),
      `// generated by variants.mjs\nimport { make } from './opt.mjs';\nexport default make(${JSON.stringify({ name, ...cfg })});\n`);
  }
  console.log('methods/v-*.mjs written');
}
